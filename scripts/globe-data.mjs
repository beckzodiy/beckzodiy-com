// Builds src/geo.js: which points of a Fibonacci sphere are land / Uzbekistan / UAE,
// plus the outlines of Uzbekistan and the UAE. Run: node scripts/globe-data.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const N = 80000
const land = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'))
const countries = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'))
const landF = feature(land, land.objects.land)
const all = feature(countries, countries.objects.countries).features
const uz = all.find(f => f.id === '860')
const ae = all.find(f => f.id === '784')

const golden = Math.PI * (3 - Math.sqrt(5))
const landBits = new Uint8Array(Math.ceil(N / 8))
const uzIdx = [], aeIdx = []
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2
  const lat = (Math.asin(y) * 180) / Math.PI
  let lon = ((golden * i) * 180 / Math.PI) % 360
  if (lon > 180) lon -= 360
  const p = [lon, lat]
  if (!geoContains(landF, p)) continue
  landBits[i >> 3] |= 1 << (i & 7)
  if (geoContains(uz, p)) uzIdx.push(i)
  else if (geoContains(ae, p)) aeIdx.push(i)
}

const outline = f => {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  return polys.map(poly => poly[0].map(([lo, la]) => [+la.toFixed(2), +lo.toFixed(2)]))
}

const out = `// generated by scripts/globe-data.mjs — do not edit
export const N = ${N}
export const LAND = '${Buffer.from(landBits).toString('base64')}'
export const UZ = ${JSON.stringify(uzIdx)}
export const AE = ${JSON.stringify(aeIdx)}
export const UZ_OUTLINE = ${JSON.stringify(outline(uz))}
export const AE_OUTLINE = ${JSON.stringify(outline(ae))}
`
writeFileSync('src/geo.js', out)
console.log('land points:', [...landBits].reduce((a, b) => a + b.toString(2).split('1').length - 1, 0), 'uz:', uzIdx.length, 'ae:', aeIdx.length, 'bytes:', out.length)
